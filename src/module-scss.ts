/**
 * Delivery of the public SCSS API to the consumer.
 *
 * Mixins have to compute breakpoints from the same numbers as the runtime, so
 * the resolved device set is written into a `buildDir` file and exposed under
 * the `#bricks-scss` alias.
 *
 * There is deliberately NO automatic prepend through
 * `vite.css.preprocessorOptions.scss.additionalData`: it applies to every
 * compiled SCSS, `<style module>` blocks included, and breaks CSS Modules
 * across the whole application — class names arrive empty
 * (`class="undefined"`) and the interface is left without styles. Verified
 * live on the playground. So the brick author writes `@use '#bricks-scss' as
 * bricks;` themselves, as the first line of their style block.
 */

import { existsSync } from 'node:fs';
import { resolve } from 'node:path';
import { addTemplate } from '@nuxt/kit';
import type { Nuxt } from '@nuxt/schema';
import type { TBricksProjectDeviceSet } from './runtime/modules/common/types/devices';

/** Alias under which the consumer sees the generated map and the mixins */
const BRICKS_SCSS_ALIAS = '#bricks-scss';

/**
 * Resolves the path to the `mixins.scss` the generated bridge forwards to.
 *
 * In the sources the file sits next to the runtime; in the built package it
 * lives as a copy in `dist/scss`: mkdist does not carry `_*.scss` partials over
 * at all and compiles non-partials to `.css`, so the runtime path in an
 * installed package holds `mixins.css`. A `@forward` at a non-existent `.scss`
 * would break the consumer build with "Can't find stylesheet to import" — so we
 * take whichever path exists, the same way the rest of the module styles do.
 *
 * @param runtimeDir - Absolute path to the module runtime directory.
 * @returns Absolute path to the mixins file.
 */
export function resolveBricksMixinsPath(runtimeDir: string): string {
    const sourcePath = resolve(runtimeDir, 'assets/scss/public/mixins.scss');

    return existsSync(sourcePath) ? sourcePath : resolve(runtimeDir, '../scss/mixins.scss');
}

/**
 * Builds the contents of the bridge file: forwards the public mixins with the
 * project device map.
 *
 * @param devices - Resolved project device set.
 * @param mixinsPath - Absolute path to the package `mixins.scss`.
 * @returns Contents of the SCSS file.
 */
export function buildBricksScssTemplate(
    devices: TBricksProjectDeviceSet,
    mixinsPath: string
): string {
    const entries = devices.map((device) => `        ${device.key}: ${device.width},`).join('\n');

    return `// Generated by the nuxt-bricks module: the project device map.
// Change it through the bricks.devices option in nuxt.config — there is nothing
// to edit here.
@forward '${mixinsPath.replace(/\\/g, '/')}' with (
    $devices: (
${entries}
    )
);
`;
}

/**
 * Registers the SCSS bridge: the device-map template and the `#bricks-scss`
 * alias.
 *
 * @param nuxt - Nuxt instance.
 * @param devices - Resolved project device set.
 * @param mixinsPath - Absolute path to the package `mixins.scss`.
 */
export function setupBricksScss(
    nuxt: Nuxt,
    devices: TBricksProjectDeviceSet,
    mixinsPath: string
): void {
    // addTemplate rather than a direct write into buildDir: buildDir is wiped
    // after setup, and a hand-written file does not survive until the build
    const template = addTemplate({
        filename: 'bricks-scss.scss',
        write: true,
        getContents: () => buildBricksScssTemplate(devices, mixinsPath),
    });

    nuxt.options.alias[BRICKS_SCSS_ALIAS] = template.dst;
}
