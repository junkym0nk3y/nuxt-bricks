/**
 * Единственный источник знания о категориях медиа для всего стека.
 *
 * Прежде эти значения жили тремя независимыми копиями — в UI-константе галереи,
 * в сторе медиа и в серверной оркестрации, — и расходились молча: сервер
 * принимал любую строку до 100 символов при колонке VARCHAR(50), а набор
 * категорий в фильтрах был хардкодом, которого не знала БД. Сам список
 * категорий теперь живёт в `bricks_media_categories`; здесь остаётся только то,
 * что обязано совпадать у клиента и сервера без запроса к базе.
 *
 * Предустановленных категорий нет: набор целиком заводит пользователь, удалить
 * можно любую, а файл без категории — законное состояние (`category: null`).
 */

/**
 * Значение фильтра «все категории». Не категория: в БД его нет, в
 * `bricks_media.category` он никогда не попадает — загрузка при активном «all»
 * уходит без категории вовсе (`null`), потому что приёмника больше нет.
 */
export const ALL_MEDIA_CATEGORIES_FILTER = 'all';

/** Максимальная длина slug'а — ровно колонка `VARCHAR(50)`. */
export const MEDIA_CATEGORY_SLUG_MAX_LENGTH = 50;

/** Максимальная длина подписи категории (столько же осмысленно показать в чипе). */
export const MEDIA_CATEGORY_LABEL_MAX_LENGTH = 50;

/**
 * Таблица транслитерации для slug'ов. Мягкий и твёрдый знаки отбрасываются
 * (в slug'е они шумят дефисами).
 */
const CYRILLIC_TRANSLITERATION: Record<string, string> = {
    а: 'a',
    б: 'b',
    в: 'v',
    г: 'g',
    д: 'd',
    е: 'e',
    ё: 'e',
    ж: 'zh',
    з: 'z',
    и: 'i',
    й: 'y',
    к: 'k',
    л: 'l',
    м: 'm',
    н: 'n',
    о: 'o',
    п: 'p',
    р: 'r',
    с: 's',
    т: 't',
    у: 'u',
    ф: 'f',
    х: 'h',
    ц: 'c',
    ч: 'ch',
    ш: 'sh',
    щ: 'sch',
    ъ: '',
    ы: 'y',
    ь: '',
    э: 'e',
    ю: 'yu',
    я: 'ya',
};

/**
 * Приводит подпись, введённую пользователем, к slug'у: латиница и цифры в
 * нижнем регистре, всё остальное — дефис. Кириллица транслитерируется, потому
 * что slug уезжает в значение фильтра и в колонку VARCHAR(50): в проекте нет
 * ни одного места, где категория ходила бы в URL в percent-кодировке.
 *
 * @param label - Подпись, введённая пользователем.
 * @returns Slug или пустая строка, если из подписи не вышло ни одного символа.
 */
export function mediaCategoryLabelToSlug(label: string): string {
    const transliterated = label
        .trim()
        .toLowerCase()
        .split('')
        .map((char) => CYRILLIC_TRANSLITERATION[char] ?? char)
        .join('');

    return transliterated
        .replace(/[^a-z0-9]+/g, '-')
        .replace(/^-+|-+$/g, '')
        .slice(0, MEDIA_CATEGORY_SLUG_MAX_LENGTH)
        .replace(/-+$/g, '');
}
