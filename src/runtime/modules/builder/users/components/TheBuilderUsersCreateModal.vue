<script setup lang="ts">
/**
 * @description The account creation modal: the username, the display name, the
 * password, the role and the "allow signing in right away" flag.
 *
 * That flag is the `isActive` of the new account, and it has a caption for the same
 * reason the other fields do: without one the checkbox does not report that unticking
 * it creates an account the server will refuse a sign-in for — rather than, say,
 * sending out an invitation.
 *
 * A form appears only where input is needed: the role and the ability to sign in of an
 * existing account are edited right in the list row, which is why the section has no
 * separate "edit the user" form at all.
 *
 * The display name is set ONLY here: the list has to be readable by names before the
 * new people sign in for the first time, yet an administrator cannot rewrite somebody
 * else's caption afterwards — a person edits their own name and photo themselves. The
 * username is set once and for all: no endpoint of the module accepts a change of it,
 * uniqueness is held by an index on `lower(username)`, and signing in goes by that
 * very string.
 *
 * The password is shown in plain text and is generated by a button: it will have to be
 * handed over to a person, and after it is saved it is readable nowhere — what lies in
 * the database is a scrypt hash.
 *
 * A decision held by the style section: the generate button stands next to the field
 * and is aligned to its bottom edge, because the field carries a caption above itself
 * and an alignment to the top would take the button up onto the label line. The
 * password form of an account keeps the same pair for the same reason.
 */

// #region Imports
// Types
import type { IUsersCreateModalProps, IUsersCreateModalEmits } from '../types/users';
import type { IBrickUiCommonProp } from '../../../ui/types/common';
import type { TBrickDemoValues } from '../../../common/types/brick';
import type { TBricksUserRole } from '../../../common/types/auth';

// Vue
import { computed, watch } from 'vue';
import { useI18n } from 'vue-i18n';

// Constants
import {
    BRICKS_DISPLAY_NAME_MAX_LENGTH,
    BRICKS_NEW_USERNAME_MAX_LENGTH,
    BRICKS_PASSWORD_MAX_LENGTH,
    BRICKS_PASSWORD_MIN_LENGTH,
} from '../../../common/constants/auth';

// Composables
import { useUsersCreateForm } from '../composables/useUsersCreateForm';

// Components
import BricksButton from '../../../ui/base/button/BricksButton.vue';
import BricksCheckbox from '../../../ui/base/checkbox/BricksCheckbox.vue';
import BricksFieldError from '../../../ui/inputs/BricksFieldError.vue';
import BricksFieldHint from '../../../ui/inputs/BricksFieldHint.vue';
import BricksInput from '../../../ui/inputs/BricksInput.vue';
import BricksModal from '../../../ui/base/modal/BricksModal.vue';
import BricksModalFooter from '../../../ui/base/modal/BricksModalFooter.vue';
import BricksModalHeader from '../../../ui/base/modal/BricksModalHeader.vue';
import BricksSelect from '../../../ui/inputs/BricksSelect.vue';
// #endregion

// #region Props
const props = withDefaults(defineProps<IUsersCreateModalProps>(), {});
// #endregion

// #region Emits
const emit = defineEmits<IUsersCreateModalEmits>();
// #endregion

// #region Data
const { t } = useI18n();

/** The order of the roles — from wide rights to narrow, as in the role menu of a row */
const ROLE_ORDER: TBricksUserRole[] = ['admin', 'editor', 'viewer'];

const {
    username,
    displayName,
    password,
    role,
    isActive,
    errors,
    generalError,
    isSubmitting,
    generatePassword,
    submitForm,
    resetToEmpty,
} = useUsersCreateForm({
    onCreated: (user) => emit('created', user),
});
// #endregion

// #region Computed
const roleOptions = computed<IBrickUiCommonProp[]>(() =>
    ROLE_ORDER.map((item) => ({ label: t(`bricks.auth.roles.${item}`), value: item }))
);

/** Every role is available for picking: there are no limits on the role of a new account */
const roleFacets = computed<string[]>(() => [...ROLE_ORDER]);
// #endregion

// #region Methods
/**
 * Closes the modal.
 */
function handleClose(): void {
    emit('close');
}

/**
 * Accepts the chosen role. The value arrives from the kit as a string, so it is
 * checked against the list of known roles: a foreign value would travel into the
 * request body as it is.
 *
 * @param value - The value of the chosen option.
 */
function handleSelectRole(value: TBrickDemoValues): void {
    const selected = ROLE_ORDER.find((item) => item === value);

    if (selected) {
        role.value = selected;
    }
}
// #endregion

// #region Lifecycle
// The form is cleared on EVERY opening rather than on a closing: a reset on closing
// would wipe the fields right under the leaving modal (`force-mount` holds it until
// the end of the animation), and a person would watch what they had typed disappear
watch(
    () => props.isOpen,
    (isOpen) => {
        if (isOpen) {
            resetToEmpty();
        }
    }
);
// #endregion
</script>

<template>
    <BricksModal
        :is-open="props.isOpen"
        :title="t('bricks.users.createModal.title')"
        variant="gradient"
        padded
        @close="handleClose"
    >
        <div :class="$style.TheBuilderUsersCreateModal">
            <BricksModalHeader @close="handleClose" />

            <form :class="$style.form" novalidate @submit.prevent="submitForm">
                <div :class="$style.field">
                    <BricksInput
                        :label="t('bricks.users.createModal.username')"
                        :value="username"
                        :max-length="BRICKS_NEW_USERNAME_MAX_LENGTH"
                        :disabled="isSubmitting"
                        :error-message="errors.username"
                        autocomplete="off"
                        @update:value="(value: string) => (username = value)"
                    />
                    <BricksFieldHint>{{
                        t('bricks.users.createModal.usernameHint')
                    }}</BricksFieldHint>
                </div>

                <div :class="$style.field">
                    <BricksInput
                        :label="t('bricks.users.createModal.displayName')"
                        :value="displayName"
                        :max-length="BRICKS_DISPLAY_NAME_MAX_LENGTH"
                        :disabled="isSubmitting"
                        :error-message="errors.displayName"
                        autocomplete="off"
                        @update:value="(value: string) => (displayName = value)"
                    />
                    <BricksFieldHint>{{
                        t('bricks.users.createModal.displayNameHint')
                    }}</BricksFieldHint>
                </div>

                <div :class="$style.field">
                    <div :class="$style.passwordRow">
                        <BricksInput
                            :class="$style.passwordInput"
                            :label="t('bricks.users.createModal.password')"
                            :value="password"
                            type="password"
                            autocomplete="new-password"
                            revealable
                            :max-length="BRICKS_PASSWORD_MAX_LENGTH"
                            :disabled="isSubmitting"
                            :error-message="errors.password"
                            @update:value="(value: string) => (password = value)"
                        />

                        <BricksButton
                            :class="$style.generateButton"
                            size="md"
                            variant="secondary"
                            type="button"
                            :disabled="isSubmitting"
                            @click="generatePassword"
                        >
                            {{ t('bricks.users.createModal.generate') }}
                        </BricksButton>
                    </div>
                    <BricksFieldHint>
                        {{
                            t('bricks.users.createModal.passwordHint', {
                                min: BRICKS_PASSWORD_MIN_LENGTH,
                            })
                        }}
                    </BricksFieldHint>
                </div>

                <div :class="$style.field">
                    <span :class="$style.label">{{ t('bricks.users.createModal.role') }}</span>
                    <BricksSelect
                        :value="role"
                        :specs="roleOptions"
                        :facets="roleFacets"
                        :disabled="isSubmitting"
                        :aria-label="t('bricks.users.createModal.role')"
                        @update:value="handleSelectRole"
                    />
                    <BricksFieldHint>{{ t('bricks.users.createModal.roleHint') }}</BricksFieldHint>
                </div>

                <div :class="$style.field">
                    <BricksCheckbox
                        :value="isActive"
                        :label="t('bricks.users.createModal.canSignIn')"
                        :disabled="isSubmitting"
                        @update:value="(value: boolean) => (isActive = value)"
                    />
                    <BricksFieldHint>{{
                        t('bricks.users.createModal.canSignInHint')
                    }}</BricksFieldHint>
                </div>

                <BricksFieldError :message="generalError" />

                <BricksModalFooter variant="inline">
                    <BricksButton
                        size="md"
                        variant="ghost"
                        type="button"
                        :disabled="isSubmitting"
                        @click="handleClose"
                    >
                        {{ t('bricks.common.cancel') }}
                    </BricksButton>

                    <BricksButton
                        size="md"
                        variant="primary"
                        type="submit"
                        :disabled="isSubmitting"
                    >
                        {{ t('bricks.users.createModal.submit') }}
                    </BricksButton>
                </BricksModalFooter>
            </form>
        </div>
    </BricksModal>
</template>

