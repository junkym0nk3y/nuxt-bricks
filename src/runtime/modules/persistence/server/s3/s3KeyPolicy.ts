/**
 * The object key policy of the S3 storage: extracting the key from a public URL
 * and checking that it belongs to the managed namespace (the module's prefixes in the
 * bucket).
 *
 * Pure functions with no runtimeConfig — used by s3PublishAdapter and by unit tests.
 * The managed namespace bounds the adapter's operations (delete/proxy/registration)
 * to its own prefixes: in a shared bucket the module cannot touch foreign objects
 * even by a valid bucket URL.
 *
 * Canonicalization: the former check was a string `startsWith` over the raw URL and
 * let `bricks-media/../x` through — the HTTP client normalized such an address into
 * an object OUTSIDE the managed namespace (reproduced through the media proxy). Now
 * the URL is parsed by the WHATWG parser (protocol/host/userinfo are matched against
 * the base explicitly; literal `.`/`..`/backslash the parser normalizes itself), the
 * key is decoded exactly once, after which dot segments, empty segments, control
 * characters, a backslash and a leftover `%` (ambiguous double encoding) are
 * rejected. The module's keys are generated by the server (`<uuid>.<ext>` for media,
 * `page-<id>-<uuid>.webp` for page previews) and always satisfy these bounds.
 */

/**
 * The bucket's base address, for extracting a key.
 */
export interface IStorageUrlBase {
    endpoint: string;
    bucket: string;
}

/**
 * The URL delimiters: they are forbidden in a managed prefix, because the public URL
 * is assembled by concatenation and everything after them goes off into the query or
 * the fragment.
 */
const URL_DELIMITERS_PATTERN = /[?#]/;

/** Control characters (C0 + DEL) and a backslash — forbidden in an object key. */
// oxlint-disable-next-line no-control-regex
const UNSAFE_KEY_CHARS_PATTERN = /[\\\u0000-\u001F\u007F]/;

/**
 * Checks that a decoded object key carries no traversal/injection primitives: dot
 * segments (`.`, `..`), empty segments, control characters, a backslash and a `%`
 * (after a single decoding a leftover `%` means ambiguous repeated encoding).
 *
 * @param key - The decoded S3 object key.
 * @returns true when the key is safe.
 */
export function isSafeStorageKey(key: string): boolean {
    if (!key || key.includes('%') || UNSAFE_KEY_CHARS_PATTERN.test(key)) {
        return false;
    }

    return key.split('/').every((segment) => segment !== '' && segment !== '.' && segment !== '..');
}

/**
 * Extracts the canonical S3 object key from a file's public URL.
 * The URL is parsed by the parser: the protocol/host/userinfo are matched against the
 * base, the query/fragment are dropped (the `?v=` cache buster is not part of the
 * key), the key is decoded once and passes `isSafeStorageKey`.
 *
 * @param url - The file's full URL.
 * @param base - The storage's endpoint and bucket.
 * @returns The canonical key, or null (a foreign origin/bucket, an unsafe key).
 */
export function extractStorageKey(url: string, base: IStorageUrlBase): string | null {
    let parsed: URL;
    let baseUrl: URL;

    try {
        parsed = new URL(url);
        baseUrl = new URL(`${base.endpoint.replace(/\/+$/, '')}/${base.bucket}/`);
    } catch {
        return null;
    }

    const sameOrigin =
        parsed.protocol === baseUrl.protocol &&
        parsed.host === baseUrl.host &&
        parsed.username === '' &&
        parsed.password === '';

    if (!sameOrigin || !parsed.pathname.startsWith(baseUrl.pathname)) {
        return null;
    }

    let key: string;

    try {
        key = decodeURIComponent(parsed.pathname.slice(baseUrl.pathname.length));
    } catch {
        return null;
    }

    return isSafeStorageKey(key) ? key : null;
}

/**
 * Checks that the key is safe and lies inside one of the module's managed prefixes
 * with a non-empty name after the prefix (the prefix itself is not a file).
 *
 * @param key - The S3 object key (decoded).
 * @param managedPrefixes - The prefixes the module owns (with a trailing `/`).
 * @returns true when the key belongs to the managed namespace.
 */
export function isManagedStorageKey(key: string, managedPrefixes: readonly string[]): boolean {
    if (!isSafeStorageKey(key)) {
        return false;
    }

    return managedPrefixes.some((prefix) => key.startsWith(prefix) && key.length > prefix.length);
}

/**
 * Looks for a violation in the set of managed prefixes: an unsafe value, a missing
 * trailing `/`, or one prefix nested in another.
 *
 * The check is mandatory because the isolation of the namespaces rests SOLELY on the
 * prefixes not overlapping. A pair like `prefix: 'bricks/'` and
 * `avatarsPrefix: 'bricks/avatars/'` looks natural, but the media library's listing
 * (`listFiles` walks `prefix`) would see the avatars as media files: the bucket
 * import would register the profile photos in the gallery, and from there any editor
 * could delete them. The promise "avatars are outside the media library" would be a
 * lie in such a configuration.
 *
 * The trailing `/` is required for the same reason: `bricks-media` without it makes
 * `bricks-media-archive/x` its own too, that is, the namespace stops being a
 * directory.
 *
 * @param prefixes - The module's named prefixes (the option's name → its value).
 * @returns The violation's text, or null when the set is correct.
 */
export function findManagedPrefixConflict(prefixes: Record<string, string>): string | null {
    const entries = Object.entries(prefixes);

    for (const [name, value] of entries) {
        // The value itself does not pass `isSafeStorageKey` by construction: the
        // trailing slash gives an empty last segment, and for an object key that is
        // forbidden. What is checked is the directory without it
        const directory = value.endsWith('/') ? value.slice(0, -1) : '';

        if (!directory || value.startsWith('/') || !isSafeStorageKey(directory)) {
            return `${name} must be a relative path ending with "/" (got "${value}")`;
        }

        // `isSafeStorageKey` lets `?` and `#` through — in a key TAKEN OUT of a URL
        // they cannot occur, the parser cuts the query and the fragment off earlier.
        // The public URL, though, is assembled by the adapter through concatenation,
        // and such a prefix would turn part of the key into a query: the link would
        // stop addressing the object, and `isOwnedUrl` would not be able to recover
        // the key — the file would become undeletable
        if (URL_DELIMITERS_PATTERN.test(value)) {
            return `${name} must not contain "?" or "#" (got "${value}")`;
        }
    }

    for (const [name, value] of entries) {
        for (const [otherName, otherValue] of entries) {
            if (name === otherName) {
                continue;
            }

            // Equality is caught by the same condition: a prefix starts with itself
            if (value.startsWith(otherValue)) {
                return `${name} ("${value}") must not be nested in ${otherName} ("${otherValue}")`;
            }
        }
    }

    return null;
}
