-- 0006_page_version_thumbnail: превью у сохранённой версии страницы.
--
-- Колонку заполняет снапшот версии (INSERT..SELECT в postgresStorageAdapter):
-- вместе со schema копируется thumbnail_url страницы на момент снимка. Снимок
-- канваса снимается ПОСЛЕ сохранения, поэтому thumbnail_url страницы — это кадр
-- того состояния, которое снапшот и сохраняет; версия получает свой снимок, а не
-- следующий.
--
-- У версий, созданных до этой миграции, снимка нет и не появится — UI рисует им
-- плейсхолдер. NULL здесь означает именно это, а не «ещё не загрузился».
ALTER TABLE bricks_page_versions ADD COLUMN IF NOT EXISTS thumbnail_url TEXT;
